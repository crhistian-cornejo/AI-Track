//! Keyboard actions and their default bindings.

use gpui::{App, KeyBinding, actions};

actions!(
    aitrack,
    [
        PlayStop,
        ToggleView,
        Undo,
        Redo,
        DeleteSelection,
        ToggleDrawTool,
        ToggleLoop,
        ToggleAssistant,
        SelectAll,
        TabDevices,
        TabPianoRoll,
        TabSteps,
        TabMixer,
        Escape,
        OpenPreferences,
        ExportAudio,
        SaveProjectAs,
        SaveProject,
        OpenProject,
        NewProject,
        ArrangeFit,
        ArrangeZoomOut,
        ArrangeZoomIn,
        AddReturnTrack,
        AddMidiTrack,
        AddAudioTrack,
        UngroupTracks,
        GroupTracks,
        SplitClip,
        ZoomIn,
        ZoomOut,
        ZoomReset,
        NudgeUp,
        NudgeDown,
        NudgeLeft,
        NudgeRight,
        SemitoneUp,
        SemitoneDown,
        OctaveUp,
        OctaveDown,
        Longer,
        Shorter,
        VelocityUp,
        VelocityDown,
        ToggleActive,
        Duplicate,
        ToggleDetail,
        ToggleDetailView,
        ShowMixer,
        TogglePalette,
        AddLibraryFolder,
        ToggleGroupFold,
        Quit,
    ]
);

/// Single-key shortcuts must not fire while a text field has the keys.
const CTX: &str = "Workspace && !TextInput";

pub fn bind(cx: &mut App) {
    let m = if cfg!(target_os = "macos") { "cmd" } else { "ctrl" };
    cx.bind_keys([
        KeyBinding::new("space", PlayStop, Some(CTX)),
        KeyBinding::new("tab", ToggleView, Some(CTX)),
        KeyBinding::new(&format!("{m}-z"), Undo, Some("Workspace")),
        KeyBinding::new(&format!("{m}-shift-z"), Redo, Some("Workspace")),
        KeyBinding::new(&format!("{m}-y"), Redo, Some("Workspace")),
        KeyBinding::new("delete", DeleteSelection, Some(CTX)),
        KeyBinding::new("backspace", DeleteSelection, Some(CTX)),
        KeyBinding::new("b", ToggleDrawTool, Some(CTX)),
        KeyBinding::new(&format!("{m}-l"), ToggleLoop, Some("Workspace")),
        KeyBinding::new(&format!("{m}-i"), ToggleAssistant, Some("Workspace")),
        KeyBinding::new(&format!("{m}-k"), TogglePalette, Some("Workspace")),
        KeyBinding::new(&format!("{m}-a"), SelectAll, Some(CTX)),
        KeyBinding::new("1", TabDevices, Some(CTX)),
        KeyBinding::new("2", TabPianoRoll, Some(CTX)),
        KeyBinding::new("3", TabSteps, Some(CTX)),
        KeyBinding::new("4", TabMixer, Some(CTX)),
        KeyBinding::new("escape", Escape, Some(CTX)),
        KeyBinding::new(&format!("{m}-,"), OpenPreferences, Some("Workspace")),
        KeyBinding::new(&format!("{m}-shift-e"), ExportAudio, Some("Workspace")),
        KeyBinding::new(&format!("{m}-="), ZoomIn, Some("Workspace")),
        KeyBinding::new(&format!("{m}-+"), ZoomIn, Some("Workspace")),
        KeyBinding::new(&format!("{m}--"), ZoomOut, Some("Workspace")),
        KeyBinding::new(&format!("{m}-0"), ZoomReset, Some("Workspace")),
        // File.
        KeyBinding::new(&format!("{m}-n"), NewProject, Some("Workspace")),
        KeyBinding::new(&format!("{m}-o"), OpenProject, Some("Workspace")),
        KeyBinding::new(&format!("{m}-s"), SaveProject, Some("Workspace")),
        KeyBinding::new(&format!("{m}-shift-s"), SaveProjectAs, Some("Workspace")),
        // Live key commands for the selection.
        KeyBinding::new("up", NudgeUp, Some(CTX)),
        KeyBinding::new("down", NudgeDown, Some(CTX)),
        KeyBinding::new("left", NudgeLeft, Some(CTX)),
        KeyBinding::new("right", NudgeRight, Some(CTX)),
        KeyBinding::new("alt-up", SemitoneUp, Some(CTX)),
        KeyBinding::new("alt-down", SemitoneDown, Some(CTX)),
        KeyBinding::new("shift-up", OctaveUp, Some(CTX)),
        KeyBinding::new("shift-down", OctaveDown, Some(CTX)),
        KeyBinding::new("shift-right", Longer, Some(CTX)),
        KeyBinding::new("shift-left", Shorter, Some(CTX)),
        KeyBinding::new(&format!("{m}-up"), VelocityUp, Some(CTX)),
        KeyBinding::new(&format!("{m}-down"), VelocityDown, Some(CTX)),
        KeyBinding::new("0", ToggleActive, Some(CTX)),
        KeyBinding::new(&format!("{m}-d"), Duplicate, Some(CTX)),
        // Clips and tracks.
        KeyBinding::new(&format!("{m}-e"), SplitClip, Some(CTX)),
        KeyBinding::new(&format!("{m}-g"), GroupTracks, Some(CTX)),
        KeyBinding::new(&format!("{m}-shift-g"), UngroupTracks, Some(CTX)),
        KeyBinding::new(&format!("{m}-t"), AddAudioTrack, Some("Workspace")),
        KeyBinding::new(&format!("{m}-shift-t"), AddMidiTrack, Some("Workspace")),
        KeyBinding::new(&format!("{m}-alt-t"), AddReturnTrack, Some("Workspace")),
        // Arrangement zoom (the interface zoom is Ctrl with the same keys).
        KeyBinding::new("=", ArrangeZoomIn, Some(CTX)),
        KeyBinding::new("+", ArrangeZoomIn, Some(CTX)),
        KeyBinding::new("-", ArrangeZoomOut, Some(CTX)),
        KeyBinding::new("w", ArrangeFit, Some(CTX)),
        // Panels.
        KeyBinding::new(&format!("{m}-alt-l"), ToggleDetail, Some("Workspace")),
        KeyBinding::new("shift-tab", ToggleDetailView, Some(CTX)),
        KeyBinding::new(&format!("{m}-alt-m"), ShowMixer, Some("Workspace")),
        KeyBinding::new(&format!("{m}-q"), Quit, None),
    ]);
    cx.on_action(|_: &Quit, cx| cx.quit());
}
