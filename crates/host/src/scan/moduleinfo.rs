//! VST3 `Contents/Resources/moduleinfo.json` (SDK 3.7.5+): lets the scanner
//! list a bundle's classes without loading its binary.
//!
//! The file is JSON5 in theory; in practice it is JSON that sometimes has
//! comments or trailing commas, which are stripped before parsing.

use std::path::Path;

use aitrack_model::PluginFormat;
use serde::Deserialize;

use crate::info::HostedPluginInfo;

#[derive(Deserialize)]
struct ModuleInfo {
    #[serde(rename = "Factory Info", default)]
    factory_info: Option<FactoryInfo>,
    #[serde(rename = "Classes", default)]
    classes: Vec<ClassInfo>,
}

#[derive(Deserialize)]
struct FactoryInfo {
    #[serde(rename = "Vendor", default)]
    vendor: String,
}

#[derive(Deserialize)]
struct ClassInfo {
    #[serde(rename = "CID")]
    cid: String,
    #[serde(rename = "Category", default)]
    category: String,
    #[serde(rename = "Name", default)]
    name: String,
    #[serde(rename = "Vendor", default)]
    vendor: String,
    #[serde(rename = "Version", default)]
    version: String,
    #[serde(rename = "Sub Categories", default)]
    sub_categories: Vec<String>,
}

pub fn path(bundle: &Path) -> std::path::PathBuf {
    bundle.join("Contents").join("Resources").join("moduleinfo.json")
}

/// Audio processor classes listed in the bundle's moduleinfo, or `None`
/// if the file is missing, unreadable or lists no audio classes.
pub fn read(bundle: &Path) -> Option<Vec<HostedPluginInfo>> {
    let text = std::fs::read_to_string(path(bundle)).ok()?;
    parse(bundle, &text)
}

pub fn parse(bundle: &Path, text: &str) -> Option<Vec<HostedPluginInfo>> {
    let info: ModuleInfo = serde_json::from_str(&relax_json(text)).ok()?;
    let factory_vendor = info.factory_info.map(|f| f.vendor).unwrap_or_default();
    let out: Vec<HostedPluginInfo> = info
        .classes
        .into_iter()
        .filter(|c| c.category == crate::vst3::AUDIO_MODULE_CLASS)
        .filter_map(|c| {
            let tuid = crate::info::hex_to_tuid(&c.cid)?;
            let is_instrument = c.sub_categories.iter().any(|s| s.eq_ignore_ascii_case("Instrument"));
            Some(HostedPluginInfo {
                format: PluginFormat::Vst3,
                uid: crate::info::tuid_to_hex(&tuid),
                name: c.name,
                vendor: if c.vendor.is_empty() { factory_vendor.clone() } else { c.vendor },
                version: c.version,
                category: c.sub_categories.join("|"),
                is_instrument,
                path: bundle.to_path_buf(),
                inputs: if is_instrument { 0 } else { 2 },
                outputs: 2,
                params: 0,
                probed: false,
            })
        })
        .collect();
    (!out.is_empty()).then_some(out)
}

/// Strip `//` and `/* */` comments and trailing commas (outside strings).
fn relax_json(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let b: Vec<char> = src.chars().collect();
    let mut i = 0;
    let mut in_str = false;
    while i < b.len() {
        let c = b[i];
        if in_str {
            out.push(c);
            if c == '\\' && i + 1 < b.len() {
                out.push(b[i + 1]);
                i += 1;
            } else if c == '"' {
                in_str = false;
            }
            i += 1;
            continue;
        }
        match c {
            '"' => {
                in_str = true;
                out.push(c);
            }
            '/' if b.get(i + 1) == Some(&'/') => {
                while i < b.len() && b[i] != '\n' {
                    i += 1;
                }
                continue;
            }
            '/' if b.get(i + 1) == Some(&'*') => {
                i += 2;
                while i + 1 < b.len() && !(b[i] == '*' && b[i + 1] == '/') {
                    i += 1;
                }
                i += 2;
                continue;
            }
            ',' => {
                let mut j = i + 1;
                while j < b.len() && b[j].is_whitespace() {
                    j += 1;
                }
                if !matches!(b.get(j), Some(']') | Some('}')) {
                    out.push(c);
                }
            }
            _ => out.push(c),
        }
        i += 1;
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"{
  // generated by moduleinfotool
  "Name": "Example",
  "Version": "1.0.0",
  "Factory Info": { "Vendor": "Example Co", "URL": "", "E-Mail": "", "Flags": { "Unicode": true, }, },
  "Compatibility": [],
  "Classes": [
    {
      "CID": "4142434445464748494A4B4C4D4E4F50",
      "Category": "Audio Module Class",
      "Name": "Example Synth",
      "Vendor": "",
      "Version": "1.2.3",
      "SDKVersion": "VST 3.7.9",
      "Sub Categories": ["Instrument", "Synth"],
      "Class Flags": 0,
      "Cardinality": 2147483647,
    },
    {
      "CID": "0000000000000000000000000000AAAA",
      "Category": "Component Controller Class",
      "Name": "Example Synth Controller",
    },
  ],
}"#;

    #[test]
    fn parses_sdk_style_moduleinfo() {
        let infos = parse(Path::new("C:/x/Example.vst3"), SAMPLE).expect("parsed");
        assert_eq!(infos.len(), 1);
        let i = &infos[0];
        assert_eq!(i.name, "Example Synth");
        assert_eq!(i.vendor, "Example Co");
        assert_eq!(i.version, "1.2.3");
        assert!(i.is_instrument);
        assert_eq!(i.category, "Instrument|Synth");
        assert_eq!(i.uid, "4142434445464748494A4B4C4D4E4F50");
        assert!(!i.probed);
    }

    #[test]
    fn relax_keeps_strings() {
        assert_eq!(relax_json(r#"{"a": "x, // y",}"#), r#"{"a": "x, // y"}"#);
    }
}
